function getStoredLanguage(): LanguageCode {
  const savedLanguage = window.localStorage.getItem('playbet-language')
  return languages.some(language => language.code === savedLanguage)
    ? savedLanguage as LanguageCode
    : 'en'
}

export const language = ref<LanguageCode>(getStoredLanguage())

export function setLanguage(nextLanguage: LanguageCode) {
  language.value = nextLanguage
  window.localStorage.setItem('playbet-language', nextLanguage)
  document.documentElement.lang = nextLanguage
  document.documentElement.dir = nextLanguage === 'fa' ? 'rtl' : 'ltr'
}

export function t(source: string, values: Record<string, string | number> = {}): string {
  let translated = language.value === 'en'
    ? source
    : translations[language.value][source] ?? source

  if (translated === source && language.value !== 'en') {
    for (const [template, localizedTemplate] of Object.entries(translations[language.value])) {
      const placeholders = [...template.matchAll(/\{(\w+)\}/g)]
      if (placeholders.length === 0) {
        continue
      }

      const pattern = template
        .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        .replace(/\\\{\w+\\\}/g, '(.+?)')
      const match = source.match(new RegExp(`^${pattern}$`))

      if (match) {
        translated = localizedTemplate
        placeholders.forEach(([placeholder], index) => {
          translated = translated.replace(placeholder, match[index + 1])
        })
        break
      }
    }
  }

  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    String(values[key] ?? placeholder)
  )
}

